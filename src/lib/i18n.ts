type Translations = typeof translations.en;
type TKey = keyof Translations;

function interpolate(str: string, vars?: Record<string, string | number>): string {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

export function t(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  const dict = translations[lang] as Record<string, string>;
  const val = dict[key] ?? (translations.en as Record<string, string>)[key] ?? key;
  return interpolate(val, vars);
}

export function p(lang: Lang, poly: { en: string; de?: string; es?: string }): string {
  return poly[lang] ?? poly.en;
}

import { getState } from "./store";

export function useT() {
  const lang: Lang = getState().lang;
  return {
    lang,
    t: (key: TKey, vars?: Record<string, string | number>) => t(lang, key, vars),
    p: (poly: { en: string; de?: string; es?: string }) => p(lang, poly),
  };
}
